"""Writes src/skins_data.h from tools/skins.json and tools/visualizations.json.

skins.json lists the skins from Microsoft's Windows Media Player 9 Series
skin gallery (windowsmedia.com and microsoft.com/windows/windowsmedia,
2002-2008), read from the Internet Archive's copies of the gallery pages:
the .wmz download URL, the preview image URL, and the gallery text.
visualizations.json is the same for the 9 Series visualization gallery
(installer .exe files), and plugins.json for the plug-in gallery, where only
Microsoft's own PowerToys have a download (the rest were sold from the
vendors' sites, which are gone)."""
import json, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
skins = json.load(open(os.path.join(here, 'skins.json'), encoding='utf-8'))

def c(s):
    out = '"'
    for b in s.encode('utf-8'):
        ch = chr(b)
        if ch in '"\\':
            out += '\\' + ch
        elif 32 <= b < 127:
            out += ch
        else:
            out += '\\%03o' % b
    return out + '"'

def local_name(url):
    n = os.path.basename(url).replace('%20', ' ')
    n = re.sub(r'[^A-Za-z0-9.]+', '_', n)
    return n

seen = set()
rows = []
for s in skins:
    f = local_name(s['url'])
    while f.lower() in seen:
        f = '_' + f
    seen.add(f.lower())
    img = s['img'].replace(':80/', '/')
    ts = s['img_ts']
    # The archive never kept windowsmedia.com's copies of the previews, only
    # microsoft.com's.
    if img.startswith('http://windowsmedia.com/9series/Personalization/'):
        img = img.replace('http://windowsmedia.com/9series/Personalization/',
                          'http://www.microsoft.com/windows/windowsmedia/9series/gettingstarted/personalization/')
        ts = '2004'
    img = img.replace('TheLastSamurai_large.jpg', 'TheLastSamurai.jpg')  # only this one was kept
    desc = s['desc'] or ('Bam! Wham! Pow!' if 'Batman' in s['name'] else '')
    rows.append('    {%s, %s,\n     %s,\n     %s, %s,\n     %s, %s, "",\n     %s, ""},' % (
        c(s['name']), c(f), c(s['url'].replace(' ', '%20')), c(ts), c(img),
        c(s['size']), c(s['by']), c(desc)))

viz = json.load(open(os.path.join(here, 'visualizations.json'), encoding='utf-8'))
vrows = []
for v in viz:
    vrows.append('    {%s, %s,\n     %s,\n     %s, %s,\n     "", %s, %s,\n     %s, ""},' % (
        c(v['name']), c(os.path.basename(v['url'])), c(v['url']), c(v['ts']), c(v['img']),
        c(v['by']), c(v['note']), c(v['desc'])))

with open(os.path.join(here, '..', 'src', 'skins_data.h'), 'w') as o:
    o.write('/* Generated by tools/gen_skins.py from tools/skins.json. Do not edit. */\n')
    o.write('static const skin_t skin_list[] = {\n')
    o.write('\n'.join(rows))
    o.write('\n};\n')
    o.write('static const skin_t viz_list[] = {\n')
    o.write('\n'.join(vrows))
    o.write('\n};\n')
plug = json.load(open(os.path.join(here, 'plugins.json'), encoding='utf-8'))
prows = []
for v in plug:
    prows.append('    {%s, %s,\n     %s,\n     %s, %s,\n     %s, %s, %s,\n     %s, %s},' % (
        c(v['name']), c(os.path.basename(v['url'])), c(v['url']), c(v['ts']), c(v['img']),
        c(v['size']), c(v['by']), c(v['note']), c(v['desc']), c(v['section'])))
with open(os.path.join(here, '..', 'src', 'skins_data.h'), 'a') as o:
    o.write('static const skin_t plug_list[] = {\n')
    o.write('\n'.join(prows))
    o.write('\n};\n')
print(len(rows), 'skins,', len(vrows), 'visualizations,', len(prows), 'plug-ins')
